#!/usr/bin/env python3
"""Render every UI SVG at 16/20/24/32/48/64/96/128 on light into one PNG.

Dark-theme icons are checked in the main-window screenshots generated by UiShotTool.
Run from the repository root:
    python scripts/RenderIconContactSheet.py

Requires Chrome or Edge. Set CHROME to override.
"""
from __future__ import annotations

import html
import os
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ICONS = ROOT / "src" / "Gui" / "Resources" / "Icons"
OUT = ROOT / "build" / "icon-contact-sheet.png"
SIZES = [16, 20, 24, 32, 48, 64, 96, 128]
CELL = 144


def browser() -> str:
    for candidate in [
        os.environ.get("CHROME"),
        r"C:\Program Files\Google\Chrome\Application\chrome.exe",
        r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
    ]:
        if candidate and Path(candidate).exists():
            return candidate
    raise SystemExit("Chrome/Edge not found; set CHROME")


def main() -> None:
    names = sorted(path.stem for path in ICONS.glob("*.svg"))
    rows = []
    for name in names:
        svg = (ICONS / f"{name}.svg").read_text(encoding="utf-8").strip()
        cells = "".join(
            f'<div class="cell"><span style="width:{size}px;height:{size}px">{svg.replace("<svg ", f"<svg width=\"{size}\" height=\"{size}\" ", 1)}</span><small>{size}</small></div>'
            for size in SIZES
        )
        rows.append(f'<div class="row"><div class="name">{html.escape(name)}</div>{cells}</div>')

    page = (
        "<!doctype html><html><head><meta charset=\"utf-8\"><style>"
        "body{margin:0;padding:20px;background:#f5f5f3;color:#151515;font:12px 'Segoe UI',sans-serif}"
        f".row{{display:flex;align-items:center;border-bottom:1px solid #e4e7e7}}"
        ".name{width:160px;flex:none;color:#6b6b66}"
        f".cell{{width:{CELL}px;height:{CELL}px;display:flex;flex-direction:column;align-items:center;justify-content:center;gap:6px;color:#1a1a19;flex:none}}"
        ".cell small{color:#8a8a84;font-size:10px}"
        "</style></head><body>" + "".join(rows) + "</body></html>"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    height = CELL * (len(names) + 2)
    with tempfile.TemporaryDirectory() as temp:
        page_path = Path(temp) / "sheet.html"
        page_path.write_text(page, encoding="utf-8")
        subprocess.run(
            [
                browser(), "--headless=new", "--disable-gpu", "--hide-scrollbars",
                "--no-first-run", "--no-default-browser-check", "--force-device-scale-factor=1",
                f"--window-size=1400,{height}", f"--user-data-dir={Path(temp) / 'profile'}",
                f"--screenshot={OUT}", page_path.as_uri(),
            ],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
